import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { env } from '../config/env.js';
import { prisma } from '../config/prisma.js';

/**
 * Where uploaded file bytes live. Metadata (owner, type, size, which message) is
 * always in the Attachment table; this layer only stores and fetches bytes by key.
 *
 * - `disk`: files under UPLOAD_DIR. Used locally and in Docker Compose, where api-1
 *   and api-2 share one volume.
 * - `database`: bytes in the StoredFile table. For hosts without a persistent disk
 *   (Render's free tier wipes its filesystem on every restart and sleep). Fine at
 *   portfolio scale; S3-compatible object storage is the step up for real traffic.
 *
 * Keys are generated by the server (`files/<uuid>.<ext>`, `avatars/<uuid>.<ext>`) and
 * never come from user input.
 */
export interface FileStorage {
  put(key: string, data: Buffer, mimeType: string): Promise<void>;
  /** Returns null when no file exists under the key. */
  get(key: string): Promise<Buffer | null>;
}

const uploadRoot = () => path.resolve(process.cwd(), env.UPLOAD_DIR);

/** Resolves a key inside UPLOAD_DIR, refusing anything that would escape it. */
export function resolveDiskPath(key: string): string | null {
  const root = uploadRoot();
  const full = path.resolve(root, key);
  return full.startsWith(root + path.sep) ? full : null;
}

export const diskStorage: FileStorage = {
  async put(key, data) {
    const full = resolveDiskPath(key);
    if (!full) throw new Error('Invalid storage key');
    await mkdir(path.dirname(full), { recursive: true });
    // 'wx' fails if the file exists, so a key collision can never overwrite a file.
    await writeFile(full, data, { flag: 'wx' });
  },
  async get(key) {
    const full = resolveDiskPath(key);
    if (!full) return null;
    try {
      return await readFile(full);
    } catch {
      return null;
    }
  },
};

export const databaseStorage: FileStorage = {
  async put(key, data, mimeType) {
    // Copy into a plain Uint8Array: Prisma's Bytes type does not accept Node's pooled Buffer type.
    await prisma.storedFile.create({ data: { key, data: new Uint8Array(data), mimeType, sizeBytes: data.length } });
  },
  async get(key) {
    const row = await prisma.storedFile.findUnique({ where: { key }, select: { data: true } });
    return row ? Buffer.from(row.data) : null;
  },
};

export const storage: FileStorage = env.STORAGE_DRIVER === 'database' ? databaseStorage : diskStorage;
